# embed_file.py
import sys

def main():
    if len(sys.argv) < 4:
        print("Usage: python embed_file.py <input_file> <output_cpp> <variable_name>")
        sys.exit(1)

    input_file = sys.argv[1]
    output_cpp = sys.argv[2]
    var_name = sys.argv[3]

    try:
        with open(input_file, "rb") as f:
            data = f.read()
    except Exception as e:
        print(f"Error reading {input_file}: {e}")
        sys.exit(1)

    # Convert bytes to hex formatting strings efficiently chunk-by-chunk
    chunks = []
    for i in range(0, len(data), 16):
        row = data[i:i+16]
        hex_row = ", ".join(f"0x{b:02x}" for b in row)
        chunks.append("    " + hex_row + ",")

    array_data = "\n".join(chunks)

    # Write the complete C++ formatting payload with null terminator
    with open(output_cpp, "w", encoding="utf-8") as f:
        f.write(f"""/* Generated by Python Baker. Do not modify. */
#include <cstddef>

extern "C" const unsigned char {var_name}[] = {{
{array_data}
    0x00
}};
extern "C" const size_t {var_name}Len = sizeof({var_name}) - 1;
""")

if __name__ == "__main__":
    main()